def _rsa_encrypt_slice(segment: bytes) -> bytes:
    pad_size = _RSA_KEY_LEN - len(segment)
    pad_buf = bytearray(pad_size)
    pad_buf[0], pad_buf[1] = 0, 2
    for i in range(pad_size - 3):
        pad_buf[2 + i] = secrets.randbelow(0xFF) + 1
    pad_buf[-1] = 0
    msg = int.from_bytes(pad_buf + segment, "big")
    return pow(msg, _RSA_E, _RSA_N).to_bytes(_RSA_KEY_LEN, "big")


def _rsa_decrypt_slice(segment: bytes) -> bytes:
    msg = int.from_bytes(segment, "big")
    ret = pow(msg, _RSA_E, _RSA_N).to_bytes(_RSA_KEY_LEN, "big")
    for i, b in enumerate(ret):
        if i != 0 and b == 0:
            return ret[i + 1 :]
    return ret


def _rsa_encrypt(plaintext: bytes) -> bytes:
    result = bytearray()
    max_slice = _RSA_KEY_LEN - 11
    while plaintext:
        chunk = plaintext[:max_slice]
        plaintext = plaintext[max_slice:]
        result.extend(_rsa_encrypt_slice(chunk))
    return bytes(result)


def _rsa_decrypt(ciphertext: bytes) -> bytearray:
    result = bytearray()
    while ciphertext:
        chunk = ciphertext[:_RSA_KEY_LEN]
        ciphertext = ciphertext[_RSA_KEY_LEN:]
        result.extend(_rsa_decrypt_slice(chunk))
    return result


def _xor_derive_key(source: bytes, size: int) -> bytes:
    key = bytearray(size)
    for i in range(size):
        key[i] = (source[i] + _XOR_KEY_SEED[size * i]) & 0xFF
        key[i] ^= _XOR_KEY_SEED[size * (size - i - 1)]
    return bytes(key)


def _xor_transform(key: bytes, data: bytearray):
    key_size = len(key)
    data_size = len(data)
    mod_size = data_size % 4
    for i in range(data_size):
        if i < mod_size:
            data[i] ^= key[i % key_size]
        else:
            data[i] ^= key[(i - mod_size) % key_size]


def m115_encode(key: bytes, plaintext: str) -> str:
    """Encode request data for M115 channel (download API)."""
    data = bytearray(plaintext.encode())
    _xor_transform(_xor_derive_key(key, 4), data)
    data.reverse()
    _xor_transform(_XOR_CLIENT_KEY, data)
    data = key + data
    return base64.b64encode(_rsa_encrypt(data)).decode()


def m115_decode(key: bytes, ciphertext: str) -> str:
    """Decode response data from M115 channel (download API)."""
    data = _rsa_decrypt(base64.b64decode(ciphertext))
    server_key, data = bytes(data[:16]), data[16:]
    _xor_transform(_xor_derive_key(server_key, 12), data)
    data.reverse()
    _xor_transform(_xor_derive_key(key, 4), data)
    return data.decode()


def generate_m115_key() -> bytes:
    """Generate a random 16-byte key for M115 channel."""
    return secrets.token_bytes(16)
